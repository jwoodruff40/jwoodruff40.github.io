#!/usr/bin/env node
// Populates data/extenders.json with Antistasi Ultimate "Extenders" (Steam Workshop items
// prefixed "A3UE") using the Steam Web API's IPublishedFileService/QueryFiles endpoint.
//
// Usage: STEAM_API_KEY=xxxx node scripts/fetch-extenders.mjs
//
// Docs: https://partner.steamgames.com/doc/webapi/IPublishedFileService#QueryFiles

const ARMA3_APPID = 107410;
const A3UE_TAG_REGEX = /a3ue/i;
const NEWEST_COUNT = 6;
const POPULAR_COUNT = 6;
const MAX_FEATURED = 10;
const DESCRIPTION_MAX_LEN = 200;

const API_KEY = process.env.STEAM_API_KEY;
if (!API_KEY) {
    console.error('Missing STEAM_API_KEY environment variable.');
    process.exit(1);
}

// EPublishedFileQueryType values (see Steamworks SDK ISteamRemoteStorage.h)
const QUERY_TYPE_RANKED_BY_PUBLICATION_DATE = 1;
const QUERY_TYPE_RANKED_BY_TOTAL_UNIQUE_SUBSCRIPTIONS = 9;

async function queryFiles(queryType, numPerPage) {
    const params = new URLSearchParams({
        key: API_KEY,
        query_type: String(queryType),
        page: '1',
        numperpage: String(numPerPage),
        appid: String(ARMA3_APPID),
        search_text: 'A3UE',
        return_short_description: 'true',
        return_previews: 'true',
        return_vote_data: 'true',
        strip_description_bbcode: 'true'
    });

    const url = `https://api.steampowered.com/IPublishedFileService/QueryFiles/v1/?${params.toString()}`;
    const res = await fetch(url);
    if (!res.ok) {
        throw new Error(`Steam API request failed (${res.status}): ${await res.text()}`);
    }
    const json = await res.json();
    return json?.response?.publishedfiledetails ?? [];
}

function isExtender(item) {
    return typeof item.title === 'string' && A3UE_TAG_REGEX.test(item.title);
}

function truncate(text, maxLen) {
    if (!text) return '';
    const clean = text.replace(/\s+/g, ' ').trim();
    if (clean.length <= maxLen) return clean;
    return `${clean.slice(0, maxLen - 1).trimEnd()}…`;
}

function toFeaturedEntry(item, category) {
    return {
        id: item.publishedfileid,
        title: item.title,
        description: truncate(item.short_description, DESCRIPTION_MAX_LEN),
        image: item.preview_url ?? null,
        url: `https://steamcommunity.com/sharedfiles/filedetails/?id=${item.publishedfileid}`,
        subscribers: item.subscriptions ?? 0,
        timeCreated: item.time_created ?? 0,
        category
    };
}

async function main() {
    const [newestRaw, popularRaw] = await Promise.all([
        queryFiles(QUERY_TYPE_RANKED_BY_PUBLICATION_DATE, 50),
        queryFiles(QUERY_TYPE_RANKED_BY_TOTAL_UNIQUE_SUBSCRIPTIONS, 50)
    ]);

    const newest = newestRaw.filter(isExtender).slice(0, NEWEST_COUNT).map(item => toFeaturedEntry(item, 'new'));
    const popular = popularRaw.filter(isExtender).slice(0, POPULAR_COUNT).map(item => toFeaturedEntry(item, 'popular'));

    const seen = new Set();
    const featured = [];
    for (const entry of [...popular, ...newest]) {
        if (seen.has(entry.id)) continue;
        seen.add(entry.id);
        featured.push(entry);
        if (featured.length >= MAX_FEATURED) break;
    }

    const output = {
        _note: 'Auto-generated by scripts/fetch-extenders.mjs via the Steam Web API (IPublishedFileService/QueryFiles). Do not hand-edit — run the script (requires a STEAM_API_KEY) or let the scheduled GitHub Action refresh this file instead.',
        generatedAt: new Date().toISOString(),
        extenders: featured
    };

    const fs = await import('node:fs/promises');
    const path = await import('node:path');
    const url = await import('node:url');
    const outPath = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..', 'data', 'extenders.json');
    await fs.writeFile(outPath, `${JSON.stringify(output, null, 2)}\n`);
    console.log(`Wrote ${featured.length} featured extenders to ${outPath}`);
}

main().catch(err => {
    console.error(err);
    process.exit(1);
});
